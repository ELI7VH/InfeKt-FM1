print("/* The cleaner's own INIT patch: a plain saw, the filters open (generated by tools/make_init.py: every byte a named\n"
      " * default there, after the development notes). Do not edit by hand. */")
print("#define INIT_PATCH_N 1u\nstatic const uint8_t INIT_PATCH[256] = {")
for i in range(0, 256, 32): print("    " + ",".join(map(str, patch[i:i+32])) + ",")
print("};")
