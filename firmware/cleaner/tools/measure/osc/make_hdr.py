"""make_hdr.py: engine/sy_cln_osc.h from the fitted numbers (osc_fit.json: clock.py, kernel.py, level.py write their
parts) and the designs (co_design.py). python3 make_hdr.py"""
import json, os
import co_design

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', '..', 'engine', 'sy_cln_osc.h')


def fl(x):
    return '%.9gf' % x if '.' in '%.9g' % x or 'e' in '%.9g' % x else '%.9g.f' % x


def main():
    F = json.load(open(os.path.join(HERE, 'osc_fit.json')))
    c1, c2 = F['kernel']['c1'], F['kernel']['c2']
    r0, dr, rows = co_design.taps(c1, c2)
    gc = co_design.clean(c1, c2)
    L = []
    w = L.append
    w('/* SPDX-License-Identifier: GPL-3.0-only */')
    w('/* CLEANER: the own oscillator\'s numbers (sy_cln_osc.inc, synth.c). GENERATED by tools/measure/osc/make_hdr.py from')
    w(' * osc_fit.json (black-box renders of the development engine\'s host engine: clock.py, kernel.py, level.py) and co_design.py */')
    w('#ifndef SY_CLN_OSC_H')
    w('#define SY_CLN_OSC_H')
    w('/* the step response C over five clock ticks: C(1) = CO_C1, C(2) = CO_C2, symmetric, straight between whole ticks')
    w(' * (kernel.py) */')
    w('#ifndef CO_C1')
    w('#define CO_C1 %s' % fl(c1))
    w('#define CO_C2 %s' % fl(c2))
    w('#endif')
    k = F['clock']
    w('/* the clock (clock.py): P ticks a cycle of osc 1, P = CO_SEG_N[k] / 2^o for osc 1\'s pitch in octave o above')
    w(' * CO_F0 x fs, k its segment there (edges CO_SEG_E, in that octave); osc 1\'s phase CO_PH_BITS bits, its step a tick a')
    w(' * whole number of the last bit, its restart at CO_T0 (cycles) */')
    w('#define CO_F0 %s' % fl(k['f0']))
    w('#define CO_SEG_K %d' % len(k['seg_n']))
    w('static const float CO_SEG_N[CO_SEG_K] = {%s};' % ', '.join(fl(x) for x in k['seg_n']))
    w('static const float CO_SEG_E[CO_SEG_K - 1] = {%s};' % ', '.join(fl(x) for x in k['seg_e']))
    w('#define CO_PH_BITS %d' % k['ph_bits'])
    w('#ifndef CO_T0')
    w('#define CO_T0 %s' % fl(k['t0']))
    w('#endif')
    h = F['level']
    w('/* high pitches (level.py): the level falls CO_HI_K a semitone from pitch CO_HI_P0; the emphasis eb x[n] - ea x[n-1] */')
    w('#ifndef CO_HI_P0')
    w('#define CO_HI_P0 %s' % fl(h['p0']))
    w('#define CO_HI_K %s' % fl(h['k']))
    w('#endif')
    w('#ifndef CO_EA')
    w('#define CO_EA %s' % fl(h['ea']))
    w('#define CO_EB %s' % fl(h['eb']))
    w('#endif')
    w('/* the table waves\' filter (a design for the step response above: co_design.py taps), per clock rate (ticks a')
    w(' * sample) */')
    w('#define CO_FIR_R0 %s' % fl(r0))
    w('#define CO_FIR_DR %s' % fl(dr))
    w('#define CO_FIR_N %d' % len(rows))
    w('static const float CO_FIR[CO_FIR_N][4] = {')
    w(',\n'.join('    {%s}' % ', '.join('%.7ff' % x for x in r) for r in rows) + '};')
    v6 = F['v6']
    r60, r6d, rows6 = co_design.taps(0.0, 0.0, co_design.R6_0, co_design.R6_D, co_design.R6_N)
    w('/* the 6-voice state (v6.py, v6load.py taps; synth.c CO_V6): osc 2\'s step response at half the ticks (osc 1: a straight line over')
    w(' * a tick, C1 = C2 = 0), and the tables\' filter for that line (co_design.py taps(0, 0), 0.75-1.05 ticks a sample) */')
    w('#ifndef CO_V6_C1')
    w('#define CO_V6_C1 %s' % fl(v6['c1_osc2']))
    w('#define CO_V6_C2 %s' % fl(v6['c2_osc2']))
    w('#endif')
    w('/* the plain oscillators (sync, FM) in the 6-voice state: a 3-tap FIR each, osc 1 and osc 2 (v6.py plain) */')
    w('#define CO_P6_1 %s' % ', '.join(fl(x) for x in v6['plain1']))
    w('#define CO_P6_2 %s' % ', '.join(fl(x) for x in v6['plain2']))
    w('#define CO_FIR6_R0 %s' % fl(r60))
    w('#define CO_FIR6_DR %s' % fl(r6d))
    w('#define CO_FIR6_N %d' % len(rows6))
    w('static const float CO_FIR6[CO_FIR6_N][4] = {')
    w(',\n'.join('    {%s}' % ', '.join('%.7ff' % x for x in r) for r in rows6) + '};')
    w('/* CLEAN\'s step, 1 - C (a design: co_design.py clean, the measured response up to 0.25 cycles a tick, nothing')
    w(' * above 0.33): CO_GC_R points a tick over 2 CO_GC_L ticks */')
    w('#define CO_GC_L %s' % fl(co_design.GC_L))
    w('#define CO_GC_R %d' % co_design.GC_R)
    vals = list(gc) + [0.0]
    w('static const float CO_GC[%d] = {' % len(vals))
    w(',\n'.join('    ' + ', '.join('%.7ff' % x for x in vals[i:i + 8]) for i in range(0, len(vals), 8)) + '};')
    w('#endif')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
