"""fit_filt.py FIT.json OUT.h: the cleaner's filter law correction from filt_fit.py's measurement of the development engine.
  CLN_FILT_CC[128]   the frequency per cutoff value against the cleaner's own law (the specification team's CUTOFF_HZ), in 1/100 cent
                     (int16): the median over the resonances 0..112 (the frequency does not depend on the resonance:
                     within 0.02 cent); a factor on the frequency after its limit to the audio band (synth.c filt_g)
  CLN_FILT_K[7][128] the damping's factor per cutoff value at the resonances CLN_FILT_KR (0, 64, 96, 112, 120, 124,
                     127), linear between them (synth.c filt_k; linear from 64 to 127 alone was 1 % off at 112). A fit
                     that does not hold (residual > 1 %, the resonance right at the top of the band: cutoff 122..126
                     at the high resonances) is replaced by its cutoff neighbours' line; filt_top.py and filt_top2.py refine those
                     on the null
The numbers come from black-box renders only (filt_fit.py), never from the development engine's source or tables."""
import sys, json
import numpy as np

KR = (0, 64, 96, 112, 120, 124, 127)
R = json.load(open(sys.argv[1]))
F, K, E = {}, {}, {}
for q in R:
    F[q['cut'], q['reso']] = q['f'] / q['f0']; K[q['cut'], q['reso']] = q['k'] / q['k0']; E[q['cut'], q['reso']] = q['resid']
x = np.arange(128)
fm = np.median([[F[c, r] for c in x] for r in (0, 32, 64, 96, 112)], 0)
cc = np.round(1200 * np.log2(fm) * 100).astype(int)
ks = []
for r in KR:
    k = np.array([K[c, r] for c in x]); ok = np.array([E[c, r] < 1e-2 and 0.5 < K[c, r] < 1.5 for c in x])
    k[~ok] = np.interp(x[~ok], x[ok], k[ok])
    ks.append(k)
    print('resonance %3d: %d fits replaced (%s)' % (r, (~ok).sum(), ' '.join(str(c) for c in x[~ok])))


def rows(v, fmt, per=16):
    return ',\n'.join('    ' + ', '.join(fmt % a for a in v[i:i + per]) for i in range(0, len(v), per))


out = ['/* SPDX-License-Identifier: GPL-3.0-only */',
       '/* GENERATED by cleaner/tools/measure/fit_filt.py from filt_fit.py (black-box renders of the development engine against the',
       ' * cleaner\'s own law; PROVENANCE.md "filter 1"), then filt_top.py and filt_top2.py. Do not edit. */',
       '#ifndef SY_CLN_FILT_H', '#define SY_CLN_FILT_H', '#include <stdint.h>',
       '#ifdef CLN_FILT_QC_HERE',
       '/* the frequency per cutoff value 0..127 against CUTOFF_HZ, in 1/100 cent (synth.c filt_g) */',
       'static const int16_t CLN_FILT_CC[128] = {', rows(cc, '%d'), '};', '#endif',
       '#ifdef CLN_FILT_K_HERE',
       '#define CLN_FILT_NR %d' % len(KR),
       'static const float CLN_FILT_KR[CLN_FILT_NR] = {' + ', '.join('%d.f' % r for r in KR) + '};',
       '/* the damping\'s factor per cutoff value at those resonances (synth.c filt_k) */',
       'static const float CLN_FILT_K[CLN_FILT_NR][128] = {' + ', '.join('{\n' + rows(k, '%.5ff', 8) + '}' for k in ks) + '};',
       '#endif', '#endif']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('1/100 cents', cc.min(), cc.max())
