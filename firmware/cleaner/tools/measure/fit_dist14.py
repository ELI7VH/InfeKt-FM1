"""fit_dist14.py CURVES.npz OUT.h: distortion types 1-4 for the cleaner from meas_dist14.py's measurement of the development engine
(its static curves at the intensities 0, 16, .., 112, 127; between them the development engine blends two curves linearly).
Each half (x > 0, x < 0) of a type keeps one shape over the intensities, scaled in and out (the shape invariance:
read off the measurement, every intensity's curve is A S(k x) within the errors printed):
    y = A_i S(k_i |x|) (signed),  S on a grid of z: 2^(CLN_D14_LO + e) (1 + q / 8), e = j / 8, q = j % 8 (eight
    points an octave, as a float's exponent and three top mantissa bits address them), linear in z between the grid
    points, S(z) = z S(z_0) / z_0 below the grid and S's last value above it.
Fitted by alternating least squares (S linear given A, k; A linear and k a 1-D search given S). The engine finds
the grid point from the float's bits (no logarithm, no square root): per intensity node a multiply, one table read
and a lerp.
Prints per curve the largest error (% of the curve's peak) and writes the header."""
import sys
import numpy as np

LO, PO, N = -3.0, 8, 113                # z from 2^-3 to 2^11, 8 points an octave
NODES = (0, 16, 32, 48, 64, 80, 96, 112, 127)


ZG = np.array([2.0 ** (LO + j // PO) * (1 + (j % PO) / PO) for j in range(N)])


def S_eval(S, z):
    return np.interp(z, np.r_[0.0, ZG], np.r_[0.0, S])


def basis(z):
    """the grid's weights for z (rows), linear in z, from 0 below the grid, the last point above it"""
    zz = np.r_[0.0, ZG]
    p = np.clip(np.searchsorted(zz, z, side='right') - 1, 0, N - 1)
    w = np.clip((z - zz[p]) / (zz[np.minimum(p + 1, N)] - zz[p]), 0, 1)
    M = np.zeros((len(z), N))
    r = np.arange(len(z))
    hi = p >= 1
    M[r[hi], p[hi] - 1] += 1 - w[hi]
    ok = p < N
    M[r[ok], np.minimum(p[ok], N - 1)] += w[ok]
    return M


def fit_half(xs, Ys):
    """xs > 0; Ys: the 9 curves' values (positive): S (N), A (9), lk (9)"""
    lk = np.log2([1.0, 1.28, 1.67, 2.17, 2.81, 3.64, 4.72, 6.13, 7.83])
    # the knee of intensity 0 near z = 1: k_0 from where the curve reaches 60 % of its end
    y0 = Ys[0]; xk = xs[np.argmax(y0 > 0.6 * y0[-1])]
    lk = lk + np.log2(1.0 / max(xk, 1e-4))
    A = np.array([y[-1] for y in Ys]); S = np.ones(N)
    for _ in range(25):
        # S given A, k: linear least squares on the grid weights (and the tail below the grid)
        rows, rhs = [], []
        for i in range(9):
            rows.append(A[i] * basis(xs * 2 ** lk[i])); rhs.append(Ys[i])
        R = np.zeros((N - 2, N)); R[np.arange(N - 2), np.arange(N - 2)] = 1; R[np.arange(N - 2), np.arange(1, N - 1)] = -2
        R[np.arange(N - 2), np.arange(2, N)] = 1     # (a light smoothness: the grid points past the data follow on)
        M = np.vstack(rows + [1e-3 * R]); r = np.concatenate(rhs + [np.zeros(N - 2)])
        S = np.linalg.lstsq(M, r, rcond=None)[0]
        S /= np.max(np.abs(S))                       # (S's peak 1: A is the curve's ceiling)
        for i in range(9):                           # A, k given S
            best = None
            for d in np.linspace(-0.08, 0.08, 33):
                s = S_eval(S, xs * 2 ** (lk[i] + d)); a = np.dot(s, Ys[i]) / np.dot(s, s)
                e = np.max(np.abs(a * s - Ys[i]))
                if best is None or e < best[0]: best = (e, d, a)
            lk[i] += best[1]; A[i] = best[2]
    errs = [np.max(np.abs(A[i] * S_eval(S, xs * 2 ** lk[i]) - Ys[i])) / np.max(Ys[i]) for i in range(9)]
    return S, A, lk, errs


if __name__ == '__main__':
    D = np.load(sys.argv[1]); x = D['x']
    sel = np.unique(np.r_[np.arange(0, len(x), 37), np.flatnonzero(np.abs(x) < 0.06)[::3]])
    xs_all = x[sel]
    out_S, out_A, out_K = [], [], []
    worst = 0
    for t in (1, 2, 3, 4):
        for sg in (1, -1):
            m = (sg * xs_all) > 0; xs = sg * xs_all[m]; o = np.argsort(xs); xs = xs[o]
            Ys = [(sg * D['y_%d_%d' % (t, it)][sel][m])[o] for it in NODES]
            S, A, lk, errs = fit_half(xs, Ys)
            worst = max(worst, max(errs))
            print('type %d %s: max error per intensity (%% of peak): %s' % (t, '+' if sg > 0 else '-', ' '.join('%.2f' % (100 * e) for e in errs)))
            out_S.append(S); out_A.append(sg * A); out_K.append(lk)

    def rows(v, fmt='%.6ff', per=8):
        return ',\n'.join('    ' + ', '.join(fmt % a for a in v[i:i + per]) for i in range(0, len(v), per))
    h = ['/* SPDX-License-Identifier: GPL-3.0-only */',
         '/* GENERATED by cleaner/tools/measure/fit_dist14.py from meas_dist14.py (black-box renders of the development engine;',
         ' * PROVENANCE.md "distortion 1-4"). Do not edit. Largest error of any curve: %.2f %% of its peak. */' % (100 * worst),
         '#ifndef SY_CLN_D14_H', '#define SY_CLN_D14_H',
         '#define CLN_D14_LO (%d)' % LO, '#define CLN_D14_PO %d' % PO, '#define CLN_D14_N %d' % N,
         'extern const float CLN_D14_S[4][2][CLN_D14_N], CLN_D14_A[4][2][9], CLN_D14_K[4][2][9];',
         '#endif', '#ifdef CLN_D14_DEFINE                    /* (sy_dist_tab.c) */',
         '/* the shapes S, [type 1-4][half: 0 x > 0, 1 x < 0][j] */',
         'const float CLN_D14_S[4][2][CLN_D14_N] = {']
    for t in range(4):
        h.append('  {{\n' + rows(out_S[2 * t]) + '\n  }, {\n' + rows(out_S[2 * t + 1]) + '\n  }},')
    h.append('};')
    h.append('/* per type, half and intensity node 0, 16, .., 112, 127: the out scale A (signed) and the in scale k */')
    h.append('const float CLN_D14_A[4][2][9] = {')
    for t in range(4):
        h.append('  {{' + ', '.join('%.6ff' % a for a in out_A[2 * t]) + '}, {' + ', '.join('%.6ff' % a for a in out_A[2 * t + 1]) + '}},')
    h.append('};')
    h.append('const float CLN_D14_K[4][2][9] = {')
    for t in range(4):
        h.append('  {{' + ', '.join('%.5ff' % 2 ** a for a in out_K[2 * t]) + '}, {' + ', '.join('%.5ff' % 2 ** a for a in out_K[2 * t + 1]) + '}},')
    h.append('};')
    h.append('#endif')
    open(sys.argv[2], 'w').write('\n'.join(h) + '\n')
