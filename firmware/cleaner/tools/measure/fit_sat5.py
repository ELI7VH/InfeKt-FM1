"""fit_sat5.py HYB.json OWN.json OUT.h: saturation type 5's law for the cleaner from meas_sat5.py's measurements of the
development engine (HYB) and of the cleaner with its own former law (OWN: the specification team's slope 1.66 x 2^(6 drv), limit piecewise linear;
the cleaner built with -DCLN_SAT5_OWN). The stage is y = clamp(g x, -b, b); g and b scale the measured slope and limit
one to one, so the development engine's are the own law's times the measured ratios:
  CLN_SAT5_G[33]  g at the drives 64, 66, .., 126, 127 (linear between them: within 0.15 % of the measurement)
  CLN_SAT5_B[9]   b / SAT_TRIM at 64, 72, .., 120, 127 (linear between them)"""
import sys, json
import numpy as np

H, O = json.load(open(sys.argv[1])), json.load(open(sys.argv[2]))
dv = np.arange(64, 128)
drv = (dv - 64) / 63.0
g_own = 1.66 * 2 ** (6 * drv)
b_own = np.where(dv < 96, 0.122 - 0.043 * (dv - 64) / 32, 0.079 - 0.001 * (dv - 96) / 31)
g = g_own * np.array(H['slope']) / np.array(O['slope'])
b = b_own * np.array(H['limit']) / np.array(O['limit'])
gn = list(range(64, 128, 2)) + [127]; bn = list(range(64, 128, 8)) + [127]
G = g[np.array(gn) - 64]; B = b[np.array(bn) - 64]
eg = np.max(np.abs(np.interp(dv, gn, G) / g - 1)); eb = np.max(np.abs(np.interp(dv, bn, B) / b - 1))
out = ['/* SPDX-License-Identifier: GPL-3.0-only */',
       '/* GENERATED by cleaner/tools/measure/fit_sat5.py from meas_sat5.py (black-box renders of the development engine and of the',
       ' * cleaner\'s own former law; PROVENANCE.md "saturation 5"). Do not edit. Linear between the nodes: the slope',
       ' * within %.2f %%, the limit within %.2f %% of the measurement at every drive. */' % (100 * eg, 100 * eb),
       '#ifndef SY_CLN_SAT5_H', '#define SY_CLN_SAT5_H',
       '/* the clip\'s slope g at the drives 64, 66, .., 126, 127 */',
       'static const float CLN_SAT5_G[33] = {' + ', '.join('%.5ff' % v for v in G) + '};',
       '/* its limit b (before SAT_TRIM) at 64, 72, .., 120, 127 */',
       'static const float CLN_SAT5_B[9] = {' + ', '.join('%.6ff' % v for v in B) + '};', '#endif']
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
print('slope err %.4f limit err %.4f' % (eg, eb))
